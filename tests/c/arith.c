#include "check.h"
#include <limits.h>

int i_add(int a, int b) { return a + b; }
unsigned u_div(unsigned a, unsigned b) { return a / b; }

int main(void) {
	int a = 7, b = -3, z = 0;
	unsigned u = 0xFFFFFFFFu, v = 3;
	char c = 127, d;
	unsigned char uc = 255;
	short s = 32767;
	unsigned short us = 65535;
	long l = -5;
	unsigned long ul = 10;
	CHECK(a + b == 4);
	CHECK(a - b == 10);
	CHECK(a * b == -21);
	CHECK(a / b == -2);
	CHECK(a % b == 1);
	CHECK(-a / 2 == -3);
	CHECK(-a % 2 == -1);
	CHECK((a & 3) == 3);
	CHECK((a | 8) == 15);
	CHECK((a ^ 5) == 2);
	CHECK((~a) == -8);
	CHECK((a << 3) == 56);
	CHECK((b >> 1) == -2);
	CHECK((u >> 28) == 15);
	CHECK(u / v == 0x55555555u);
	CHECK(u % 10 == 5);
	CHECK(u_div(0x80000000u, 2) == 0x40000000u);
	CHECK(u > 1);
	CHECK(b < 1);
	CHECK(!(u < 1));
	CHECK((unsigned)b > 1u);
	CHECK(-1 < 0);
	CHECK(INT_MAX + 1 == INT_MIN);
	CHECK((unsigned)INT_MIN == 0x80000000u);
	CHECK(UINT_MAX + 1u == 0);
	c++;
	CHECK(c == -128);
	d = (char)200;
	CHECK(d == -56);
	uc++;
	CHECK(uc == 0);
	s++;
	CHECK(s == -32768);
	us++;
	CHECK(us == 0);
	CHECK((unsigned char)-1 == 255);
	CHECK((signed char)0x80 == -128);
	CHECK((short)0x18000 == -32768);
	CHECK((unsigned short)-1 == 65535);
	CHECK(sizeof(char) == 1 && sizeof(short) == 2 && sizeof(int) == 4 && sizeof(long) == 4 && sizeof(void *) == 4);
	CHECK(l * 2 == -10);
	CHECK(ul - 11 == 0xFFFFFFFFu);
	CHECK(i_add(INT_MAX, 1) == INT_MIN);
	CHECK(z == 0 && !z && !!a);
	CHECK((a > b) == 1 && (a < b) == 0 && (a >= 7) && (a <= 7) && (a != b));
	CHECK((1 && 0) == 0 && (1 || 0) == 1 && (0 || 0) == 0);
	a = 10;
	a += 5;
	CHECK(a == 15);
	a -= 3;
	CHECK(a == 12);
	a *= 2;
	CHECK(a == 24);
	a /= 5;
	CHECK(a == 4);
	a %= 3;
	CHECK(a == 1);
	a <<= 4;
	CHECK(a == 16);
	a >>= 2;
	CHECK(a == 4);
	a |= 3;
	CHECK(a == 7);
	a &= 5;
	CHECK(a == 5);
	a ^= 1;
	CHECK(a == 4);
	CHECK(a++ == 4 && a == 5);
	CHECK(++a == 6);
	CHECK(a-- == 6 && a == 5);
	CHECK(--a == 4);
	u = 0;
	u -= 1;
	CHECK(u == 0xFFFFFFFFu);
	u >>= 31;
	CHECK(u == 1);
	b = -16;
	b >>= 2;
	CHECK(b == -4);
	c = 100;
	c += 100;
	CHECK(c == -56);
	CHECK((a, b) == -4);
	CHECK((a > 0 ? 10 : 20) == 10);
	CHECK(0x7FFFFFFF * 2 == -2);
	CHECK(017 == 15 && 0x1F == 31 && 'A' == 65 && '\n' == 10 && '\x41' == 'A' && '\101' == 'A');
	CHECK(-(-5) == 5 && +5 == 5);
	CHECK(10 / 3 * 3 + 10 % 3 == 10);
	CHECK(1 + 2 * 3 - 4 / 2 == 5);
	CHECK((1 << 31) < 0);
	CHECK((1u << 31) > 0);
	CHECK(5 / -2 == -2 && 5 % -2 == 1 && -5 / -2 == 2);
	DONE();
}
