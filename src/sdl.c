static void key_push(int c) {
	if (((kt + 1) & 255) == kh) return;
	keyq[kt] = c;
	kt = (kt + 1) & 255;
}

int sdl_key_avail(void) {
	return kh != kt;
}

int sdl_key(void) {
	int c;
	if (kh == kt) return 0;
	c = keyq[kh];
	kh = (kh + 1) & 255;
	return c;
}

int sdl_open(void) {
	if (SDL_Init(SDL_INIT_VIDEO)) return -1;
	win = SDL_CreateWindow("TORTOISE", SDL_WINDOWPOS_UNDEFINED, SDL_WINDOWPOS_UNDEFINED, 640, 480, 0);
	if (!win) return -1;
	ren = SDL_CreateRenderer(win, -1, 0);
	if (!ren) return -1;
	tex = SDL_CreateTexture(ren, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STREAMING, 640, 480);
	if (!tex) return -1;
	SDL_StartTextInput();
	return 0;
}

static void draw_char(int col, int row, int ch) {
	const uint8_t *g;
	if (ch < 32 || ch > 127) ch = 32;
	g = font8[ch - 32];
	for (int y = 0; y < 16; y++) {
		uint8_t bits = g[y / 2];
		uint32_t *p = pix + (row * 16 + y) * 640 + col * 8;
		for (int x = 0; x < 8; x++)
			if (bits & (1 << x)) p[x] = 0x00FFFFFF;
	}
}

void sdl_frame(uint8_t *ram, uint32_t ram_size, uint32_t fb_addr, uint32_t ctrl) {
	SDL_Event e;
	while (SDL_PollEvent(&e)) {
		if (e.type == SDL_QUIT) {
			cpu_stop(0);
		} else if (e.type == SDL_TEXTINPUT) {
			for (const char *s = e.text.text; *s; s++)
				if ((unsigned char)*s < 128) key_push(*s);
		} else if (e.type == SDL_KEYDOWN) {
			SDL_Keycode k = e.key.keysym.sym;
			if (k == SDLK_RETURN) key_push('\n');
			else if (k == SDLK_BACKSPACE) key_push(8);
			else if (k == SDLK_TAB) key_push('\t');
			else if (k == SDLK_ESCAPE) key_push(27);
			else if ((e.key.keysym.mod & KMOD_CTRL) && k >= 'a' && k <= 'z') key_push(k - 'a' + 1);
		}
	}
	if (!(ctrl & 1)) return;
	if ((uint64_t)fb_addr + sizeof(pix) <= ram_size) {
		const uint8_t *s = ram + fb_addr;
		for (int i = 0; i < 640 * 480; i++)
			pix[i] = (uint32_t)s[i * 4] | ((uint32_t)s[i * 4 + 1] << 8) | ((uint32_t)s[i * 4 + 2] << 16);
	} else {
		memset(pix, 0, sizeof(pix));
	}
	if ((ctrl & 2) && VIDEO_BASE + VIDEO_SIZE <= ram_size)
		for (int r = 0; r < 25; r++)
			for (int c = 0; c < 80; c++) draw_char(c, r, ram[VIDEO_BASE + r * 80 + c]);
	SDL_UpdateTexture(tex, NULL, pix, 640 * 4);
	SDL_RenderClear(ren);
	SDL_RenderCopy(ren, tex, NULL, NULL);
	SDL_RenderPresent(ren);
}
