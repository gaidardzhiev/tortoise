.include "ext_inc.asm"
CLI
LOAD32 R0, EVT
MTCR CR1, R0
LOAD32 R0, 0x8000
MTCR CR4, R0
setvec 14, h_pf
setvec 48, h_sys
setvec 49, h_ufail
setvec 13, h_ufail
LOAD32 R1, 0x10000
LOAD32 R2, 0
zl:
STW [R1], R2
ADD32 R1, 4
CMP32 R1, 0x16000
BLO zl
LOAD32 R1, 0x11000
LOAD32 R2, 0x0000000B
im:
STW [R1], R2
ADD32 R1, 4
ADD32 R2, 0x1000
CMP32 R2, 0x0010000B
BLO im
LOAD32 R1, 0x10000
LOAD32 R2, 0x11001
STW [R1], R2
LOAD32 R2, 0x13001
STW [R1 + 4], R2
LOAD32 R2, 0x12001
STW [R1 + 0xF00], R2
LOAD32 R2, 0x14001
STW [R1 + 0x7FC], R2
LOAD32 R1, 0x12000
LOAD32 R2, 0xF0007003
STW [R1 + 28], R2
LOAD32 R1, 0x13000
LOAD32 R2, 0x0005000F
STW [R1], R2
LOAD32 R1, 0x14000
LOAD32 R2, 0x00060007
STW [R1 + 0xFF8], R2
LOAD32 R0, 0x10000
MTCR CR3, R0
LOAD32 R0, 5
MTCR CR0, R0
LOAD32 R7, 0
LOAD32 R0, 0x7FFFF000
PUSH32 R0
LOAD32 R0, 0x20
PUSH32 R0
LOAD32 R0, 0x00400000
PUSH32 R0
IRET
fail:
putc 0x0046
poweroff 1
h_ufail:
JMP32 fail
h_pf:
MFCR R4, CR2
CMP32 R4, 0x00800010
BNE fail
MFCR R4, CR7
CMP32 R4, 0x60E
BNE fail
LOAD32 R4, 0x10000
LOAD32 R5, 0x15001
STW [R4 + 8], R5
LOAD32 R4, 0x15000
LOAD32 R5, 0x00070007
STW [R4], R5
MFCR R4, CR2
INVLPG R4
ADD32 R7, 1
IRET
h_sys:
CMP32 R7, 1
BNE fail
LOAD32 R4, 0x70010
LDW R5, [R4]
CMP32 R5, 0x600DF00D
BNE fail
LOAD32 R4, 0x15000
LDW R5, [R4]
AND32 R5, 0x30
CMP32 R5, 0x30
BNE fail
LOAD32 R4, 0x13000
LDW R5, [R4]
AND32 R5, 0x30
CMP32 R5, 0x10
BNE fail
LOAD32 R4, 0x14000
LDW R5, [R4 + 0xFF8]
AND32 R5, 0x30
CMP32 R5, 0x30
BNE fail
putc 0x0048
poweroff 0
.org 0x50000
ustart:
LOAD32 R1, 0x00800000
LOAD32 R2, 0x600DF00D
STW [R1 + 16], R2
LDW R3, [R1 + 16]
CMP32 R3, R2
BNE ubad
PUSH32 R3
POP32 R4
CMP32 R4, R2
BNE ubad
SYSCALL
ubad:
INT 49
