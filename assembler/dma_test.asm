.include "ext_inc.asm"
.equ UART, 0xF0002000
.equ DISK, 0xF0003000
CLI
LOAD32 R0, EVT
MTCR CR1, R0
setvec 35, h_disk
LOAD32 R0, 1
MTCR CR0, R0
LOAD32 R6, PIC
LOAD32 R0, 8
STW [R6 + 4], R0
LOAD32 R1, 0x30000
LOAD32 R2, 0x01020304
fill:
STW [R1], R2
ADD32 R2, 0x04040404
ADD32 R1, 4
CMP32 R1, 0x30400
BLO fill
LOAD32 R7, DISK
LDW R0, [R7 + 0x14]
CMP32 R0, 256
BNE fail
LOAD32 R0, 5
STW [R7], R0
LOAD32 R0, 2
STW [R7 + 4], R0
LOAD32 R0, 0x30000
STW [R7 + 8], R0
LOAD32 R4, 0
RDCYC R3
LOAD32 R0, 2
STW [R7 + 0x0C], R0
LDW R0, [R7 + 0x10]
CMP32 R0, 1
BNE fail
STI
w1:
CMP32 R4, 0
BNE w1.ok
WFI
JMP32 w1
w1.ok:
CLI
RDCYC R2
SUB32 R2, R3
CMP32 R2, 2000
BLO fail
CMP32 R5, 4
BNE fail
LOAD32 R0, 0x40000
STW [R7 + 8], R0
LOAD32 R4, 0
LOAD32 R0, 1
STW [R7 + 0x0C], R0
STI
w2:
CMP32 R4, 0
BNE w2.ok
WFI
JMP32 w2
w2.ok:
CLI
CMP32 R5, 4
BNE fail
LOAD32 R1, 0x30000
cmp:
LDW R2, [R1]
LDW R3, [R1 + 0x10000]
CMP32 R2, R3
BNE fail
ADD32 R1, 4
CMP32 R1, 0x30400
BLO cmp
LOAD32 R0, 256
STW [R7], R0
LOAD32 R0, 1
STW [R7 + 4], R0
LOAD32 R4, 0
STW [R7 + 0x0C], R0
STI
w3:
CMP32 R4, 0
BNE w3.ok
WFI
JMP32 w3
w3.ok:
CLI
CMP32 R5, 2
BNE fail
LOAD32 R0, 255
STW [R7], R0
LOAD32 R0, 0x000FFF00
STW [R7 + 8], R0
LOAD32 R4, 0
LOAD32 R0, 1
STW [R7 + 0x0C], R0
STI
w4:
CMP32 R4, 0
BNE w4.ok
WFI
JMP32 w4
w4.ok:
CLI
CMP32 R5, 2
BNE fail
LOAD32 R7, UART
LOAD32 R0, 'F'
STW [R7], R0
poweroff 0
fail:
LOAD32 R7, UART
LOAD32 R0, '!'
STW [R7], R0
poweroff 1
h_disk:
LDW R5, [R7 + 0x10]
LOAD32 R0, 0
STW [R7 + 0x10], R0
LDW R0, [R7 + 0x10]
CMP32 R0, 0
BNE fail
LOAD32 R0, 8
STW [R6 + 8], R0
LOAD32 R4, 1
IRET
