.include "ext_inc.asm"
CLI
LOAD32 R0, EVT
MTCR CR1, R0
setvec 32, h_t
LOAD32 R0, 1
MTCR CR0, R0
LOAD32 R6, PIC
LOAD32 R0, 1
STW [R6 + 4], R0
LOAD32 R6, TIMER
LOAD32 R0, 1000
STW [R6 + 12], R0
LOAD32 R0, 100
STW [R6 + 4], R0
LOAD32 R0, 1
STW [R6 + 8], R0
LOAD32 R5, 0
STI
loop:
WFI
CMP32 R5, 5
BLO loop
RDCYC R1
CMP32 R1, 500000
BLO fail
CMP32 R1, 501000
BHS fail
CLI
WFI
RDCYC R2
SUB32 R2, R1
CMP32 R2, 99000
BLO fail
LOAD32 R6, PIC
LDW R0, [R6]
CMP32 R0, 1
BNE fail
RDCYC R1
WFI
RDCYC R2
SUB32 R2, R1
CMP32 R2, 2
BNE fail
STI
NOP
CMP32 R5, 6
BNE fail
putc 0x005A
poweroff 0
fail:
putc 0x0046
poweroff 1
h_t:
ADD32 R5, 1
LOAD32 R4, PIC
LOAD32 R0, 1
STW [R4 + 8], R0
IRET
