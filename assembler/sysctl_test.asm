LOAD32 R0, 0xF0007000
LOAD32 R1, [R0 + 4]
CMP32 R1, 0x00100000
JNZ sys_fail
LOAD32 R1, [R0 + 8]
CMP32 R1, 2
JNZ sys_fail
LOAD R2, 0x0059
OUT R2, 0xFF00
LOAD R3, 0
STORE32 [R0 + 0], R3
HALT
sys_fail:
LOAD R2, 0x0046
OUT R2, 0xFF00
LOAD R3, 1
STORE32 [R0 + 0], R3
HALT
